"""Writes nosushi/Data.hx from the asset pipeline output (clips.json, meta.json).
usage: nosushi_data.py <out dir of nosushi_assets.py> <Data.hx>"""
import sys, json, os

OUT, DST = sys.argv[1], sys.argv[2]
clips = json.load(open(os.path.join(OUT, 'clips.json')))
meta = json.load(open(os.path.join(OUT, 'meta.json')))


def js_string(v):
    """JSON in a double quoted Haxe string (no interpolation in those)"""
    s = json.dumps(v, separators=(',', ':'), ensure_ascii=True)
    return s.replace('\\', '\\\\').replace('"', '\\"')


def floats(a):
    return '[' + ', '.join(repr(float(v)) for v in a) + ']'


names = meta['clipNames']
lines = [
    'package nosushi;',
    '',
    '// generated by .opencode/skills/flash-port/scripts/examples/nosushi/nosushi_data.py from the original gfx.swf (do not',
    '// edit)',
    'class Data {',
    '\tstatic var _clips:Dynamic = null;',
    '\tstatic var _fonts:Dynamic = null;',
    '',
    '\t// timelines of the symbols of gfx.swf (see arkadeo.Clip)',
    '\tpublic static function clips():Dynamic {',
    '\t\tif (_clips == null)',
    '\t\t\t_clips = haxe.Json.parse(CLIPS);',
    '\t\treturn _clips;',
    '\t}',
    '',
    '\t// the glyphs of the points (arkadeo.TextField): the device font "arial" of the original, bold 18 (pts)',
    '\tpublic static function fonts():Dynamic {',
    '\t\tif (_fonts == null)',
    '\t\t\t_fonts = haxe.Json.parse(FONTS);',
    '\t\treturn _fonts;',
    '\t}',
    '',
    '\t// the clips of the gfx.* classes',
]
for k in ('Bloc', 'Bonus', 'Plate', 'Explode'):
    lines.append('\tpublic static inline var %s = "%s";' % (k.upper(), names[k]))
blk = meta['blk']
lines += [
    '',
    '\t// Game.flatten of a Bloc (picture `blk` 1 + (food * 5) + bonus): the top left of its bounds, where the Bitmap is put',
    '\tpublic static var BLK_X:Array<Float> = %s;' % floats([b[0] for b in blk]),
    '\tpublic static var BLK_Y:Array<Float> = %s;' % floats([b[1] for b in blk]),
    '',
    '\t// the pictures of the `_moves` field of gfx.Bg (leftPlay 0 - 20), their top left in the stage',
    '\tpublic static inline var MOVES_X = %d;' % meta['moves'][0],
    '\tpublic static inline var MOVES_Y = %d;' % meta['moves'][1],
    '',
    '\tstatic var CLIPS = "%s";' % js_string(clips),
    '\tstatic var FONTS = "%s";' % js_string(meta['fonts']),
    '}',
    '',
]
os.makedirs(os.path.dirname(DST), exist_ok=True)
open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('Data.hx %d bytes (clips %d, fonts %d)' % (sum(len(l) + 1 for l in lines), len(js_string(clips)),
                                               len(js_string(meta['fonts']))))
