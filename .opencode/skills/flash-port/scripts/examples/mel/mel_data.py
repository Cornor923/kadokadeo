"""Writes mel/Art.hx from the asset pipeline output (clips.json, meta.json, ld.npy).
usage: mel_data.py <out dir of mel_assets.py> <Art.hx>"""
import sys, json, os, zlib, base64
import numpy as np

OUT, DST = sys.argv[1], sys.argv[2]
clips = json.load(open(os.path.join(OUT, 'clips.json')))
meta = json.load(open(os.path.join(OUT, 'meta.json')))
ld = np.load(os.path.join(OUT, 'ld.npy'))


def js_string(v):
    """JSON in a double quoted Haxe string (no interpolation in those)"""
    s = json.dumps(v, separators=(',', ':'), ensure_ascii=True)
    return s.replace('\\', '\\\\').replace('"', '\\"')


# level design: the RGB of each pixel (3 bytes, row by row), deflated
raw = np.stack([(ld >> 16) & 255, (ld >> 8) & 255, ld & 255], axis=-1).astype(np.uint8).tobytes()
ldz = base64.b64encode(zlib.compress(raw, 9)).decode('ascii')

lines = [
    'package mel;',
    '',
    '// generated by .opencode/skills/flash-port/scripts/examples/mel/mel_data.py from the original game.swf (do not edit)',
    'class Art {',
    '\tstatic var _clips:Dynamic = null;',
    '\tstatic var _meta:Dynamic = null;',
    '',
    '\t// timelines of the Flash symbols (see Clip)',
    '\tpublic static function clips():Dynamic {',
    '\t\tif (_clips == null)',
    '\t\t\t_clips = haxe.Json.parse(CLIPS);',
    '\t\treturn _clips;',
    '\t}',
    '',
    '\t// measured in the SWF: platform pieces, planes, saw blade frames (McCache), _hit boxes, power up rectangles,',
    '\t// glyphs of the embedded fonts, height sign',
    '\tpublic static function meta():Dynamic {',
    '\t\tif (_meta == null)',
    '\t\t\t_meta = haxe.Json.parse(META);',
    '\t\treturn _meta;',
    '\t}',
    '',
    '\t// Data.ldBmp (BmpLd: gfx/ld.png): %d x %d pixels, RGB (0 where transparent), deflated' % (ld.shape[1], ld.shape[0]),
    '\tpublic static inline var LD_W = %d;' % ld.shape[1],
    '\tpublic static inline var LD_H = %d;' % ld.shape[0],
    '\tpublic static var LD = "%s";' % ldz,
    '',
    '\tstatic var CLIPS = "%s";' % js_string(clips),
    '\tstatic var META = "%s";' % js_string(meta),
    '}',
    '',
]
open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('Art.hx %d bytes (ld %d, clips %d, meta %d)' % (sum(len(l) + 1 for l in lines), len(ldz), len(js_string(clips)), len(js_string(meta))))
