"""Writes fafi360/Data.hx from the asset pipeline output (clips.json, meta.json).
usage: fafi360_data.py <out dir of fafi360_assets.py> <Data.hx>"""
import sys, json, os

OUT, DST = sys.argv[1], sys.argv[2]
clips = json.load(open(os.path.join(OUT, 'clips.json')))
meta = json.load(open(os.path.join(OUT, 'meta.json')))


def js_string(v):
    """JSON in a double quoted Haxe string (no interpolation in those)"""
    s = json.dumps(v, separators=(',', ':'), ensure_ascii=True)
    return s.replace('\\', '\\\\').replace('"', '\\"')


def hx_string(v):
    return json.dumps(v, ensure_ascii=False)


texts = '\n'.join('\t\t%s => %s,' % (hx_string(k), hx_string(v)) for k, v in meta['texts'].items())
ann = meta['annonce']

lines = [
    'package fafi360;',
    '',
    '// generated by .opencode/skills/flash-port/scripts/examples/fafi360/fafi360_data.py from the original game.swf and',
    '// texts.fr.xml (do not edit)',
    'class Data {',
    '\tstatic var _clips:Dynamic = null;',
    '\tstatic var _fonts:Dynamic = null;',
    '',
    '\t// timelines of the symbols of the library (lib.*, see arkadeo.Clip)',
    '\tpublic static function clips():Dynamic {',
    '\t\tif (_clips == null)',
    '\t\t\t_clips = haxe.Json.parse(CLIPS);',
    '\t\treturn _clips;',
    '\t}',
    '',
    '\t// the glyphs of the embedded fonts (arkadeo.TextField): small 16, big 8, time 8 (Game.createField), volter 36 (the',
    '\t// _field of lib.Annonce)',
    '\tpublic static function fonts():Dynamic {',
    '\t\tif (_fonts == null)',
    '\t\t\t_fonts = haxe.Json.parse(FONTS);',
    '\t\treturn _fonts;',
    '\t}',
    '',
    '\t// the _field of lib.Annonce: its place in the clip (between _bg and _illu), its box, colour and size',
    '\tpublic static inline var ANNONCE_X = %s;' % repr(float(ann['x'])),
    '\tpublic static inline var ANNONCE_Y = %s;' % repr(float(ann['y'])),
    '\tpublic static inline var ANNONCE_W = %s;' % repr(float(ann['w'])),
    '\tpublic static inline var ANNONCE_H = %s;' % repr(float(ann['h'])),
    '\tpublic static inline var ANNONCE_COLOR = 0x%06X;' % ann['color'],
    '',
    '\t// texts.fr.xml (Lang)',
    '\tpublic static final TEXTS:Map<String, String> = [',
    texts,
    '\t];',
    '',
    '\tstatic var CLIPS = "%s";' % js_string(clips),
    '\tstatic var FONTS = "%s";' % js_string(meta['fonts']),
    '}',
    '',
]
os.makedirs(os.path.dirname(DST), exist_ok=True)
open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('Data.hx %d bytes (clips %d, fonts %d, texts %d)' % (sum(len(l) + 1 for l in lines), len(js_string(clips)),
                                                           len(js_string(meta['fonts'])), len(meta['texts'])))
