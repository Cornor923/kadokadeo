"""Writes charlottesquest/Data.hx from the asset pipeline output (clips.json, meta.json).
usage: charlottesquest_data.py <out dir of charlottesquest_assets.py> <Data.hx>"""
import sys, json, os

OUT, DST = sys.argv[1], sys.argv[2]
clips = json.load(open(os.path.join(OUT, 'clips.json')))
meta = json.load(open(os.path.join(OUT, 'meta.json')))


def js_string(v):
    """JSON in a double quoted Haxe string (no interpolation in those)"""
    s = json.dumps(v, separators=(',', ':'), ensure_ascii=True)
    return s.replace('\\', '\\\\').replace('"', '\\"')


def hx_string(v):
    return json.dumps(v, ensure_ascii=False)


texts = '\n'.join('\t\t%s => %s,' % (hx_string(k), hx_string(v)) for k, v in meta['texts'].items())
levels = []
for g in ('horizontal', 'vertical', 'toUp', 'bedroom'):
    rows = ',\n'.join('\t\t\t[%s]' % ', '.join(hx_string(r) for r in fr) for fr in meta['levels'][g])
    levels.append('\t\t%s => [\n%s\n\t\t],' % (hx_string(g), rows))

lines = [
    'package charlottesquest;',
    '',
    '// generated by .opencode/skills/flash-port/scripts/examples/charlottesquest/charlottesquest_data.py from the original',
    '// game.swf, levels.png and texts.fr.xml (do not edit)',
    'class Data {',
    '\tstatic var _clips:Dynamic = null;',
    '\tstatic var _fonts:Dynamic = null;',
    '\tstatic var _cache:Dynamic = null;',
    '',
    '\t// timelines of the symbols of the library (lib.*, see arkadeo.Clip)',
    '\tpublic static function clips():Dynamic {',
    '\t\tif (_clips == null)',
    '\t\t\t_clips = haxe.Json.parse(CLIPS);',
    '\t\treturn _clips;',
    '\t}',
    '',
    '\t// the glyphs of the embedded font "def" 16 (Game.createField, arkadeo.TextField)',
    '\tpublic static function fonts():Dynamic {',
    '\t\tif (_fonts == null)',
    '\t\t\t_fonts = haxe.Json.parse(FONTS);',
    '\t\treturn _fonts;',
    '\t}',
    '',
    '\t// the animations of Entity.cacheAnims: key -> {size: the side of the bitmap, labels: [[label, frames, animation]]}',
    '\tpublic static function cache():Dynamic {',
    '\t\tif (_cache == null)',
    '\t\t\t_cache = haxe.Json.parse(CACHE);',
    '\t\treturn _cache;',
    '\t}',
    '',
    '\t// the plans of the rooms: the slices of levels.png (Game.new: SpriteLib.sliceUnit in units of Room.CWID x Room.CHEI),',
    '\t// one string per row, "1" = a wall (a white pixel)',
    '\tpublic static final LEVELS:Map<String, Array<Array<String>>> = [',
    '\n'.join(levels),
    '\t];',
    '',
    '\t// the placement of the _smc of lib.Tourelle (Turret: basePtX, basePtY)',
    '\tpublic static final TOURELLE_SMC = %s;' % json.dumps(meta['tourelle_smc']),
    '',
    '\t// texts.fr.xml (Lang)',
    '\tpublic static final TEXTS:Map<String, String> = [',
    texts,
    '\t];',
    '',
    '\tstatic var CLIPS = "%s";' % js_string(clips),
    '',
    '\tstatic var FONTS = "%s";' % js_string(meta['fonts']),
    '',
    '\tstatic var CACHE = "%s";' % js_string(meta['cache']),
    '}',
    '',
]
open(DST, 'w', newline='\n', encoding='utf-8').write('\n'.join(lines))
print('Data.hx: %d clips, %d cached animations' % (len(clips), len(meta['cache'])))
