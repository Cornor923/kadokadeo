"""Writes greenwitch/Data.hx from the asset pipeline output (meta.json).
usage: greenwitch_data.py <out dir of greenwitch_assets.py> <Data.hx>"""
import sys, json, os

OUT, DST = sys.argv[1], sys.argv[2]
meta = json.load(open(os.path.join(OUT, 'meta.json'), encoding='utf-8'))


def js_string(v):
    """JSON in a double quoted Haxe string (no interpolation in those)"""
    s = json.dumps(v, separators=(',', ':'), ensure_ascii=True)
    return s.replace('\\', '\\\\').replace('"', '\\"')


def hx_string(v):
    return json.dumps(v, ensure_ascii=False)


texts = '\n'.join('\t\t%s => %s,' % (hx_string(k), hx_string(v)) for k, v in meta['texts'].items())
league = '\n'.join('\t\t[%s],' % ','.join('0x%06X' % v for v in plan) for plan in meta['league'])
sounds = ', '.join(hx_string(s) for s in meta['sounds'])

lines = [
    'package greenwitch;',
    '',
    '// generated by .opencode/skills/flash-port/scripts/examples/greenwitch/greenwitch_data.py from the original levels.png,',
    '// levelInfos.xml, texts.fr.xml and the font of obj/greenwitchResources.swf (do not edit)',
    'class Data {',
    '\tstatic var _fonts:Dynamic = null;',
    '',
    '\t// the glyphs of the embedded font "small" 16 (Play.createField) and the pictures of their outline (arkadeo.TextField)',
    '\tpublic static function fonts():Dynamic {',
    '\t\tif (_fonts == null)',
    '\t\t\t_fonts = haxe.Json.parse(FONTS);',
    '\t\treturn _fonts;',
    '\t}',
    '',
    '\t// the plans of the 3 dungeons of the League (Level.createLeagueLevel: the 32 x 32 at (id x 32, 32) of levels.png), one',
    '\t// RGB colour per square, row by row',
    '\tpublic static final LEAGUE_LEVELS:Array<Array<Int>> = [',
    league,
    '\t];',
    '',
    '\t// the attach point of the staff in the frames of the witch (Hero.new: its magenta pixel), x then y by frame',
    '\tpublic static final HERO_ATTACH = [%s];' % ', '.join(str(v) for v in meta['heroAttach']),
    '',
    '\t// levelInfos.xml (Level.initXml: the assets of the walls, the props)',
    '\tpublic static final LEVEL_INFOS = %s;' % hx_string(meta['levelInfos']),
    '',
    '\t// texts.fr.xml (Lang)',
    '\tpublic static final TEXTS:Map<String, String> = [',
    texts,
    '\t];',
    '',
    '\t// the sounds of public/assets/sound/greenwitch (S.BANK)',
    '\tpublic static final SOUNDS = [%s];' % sounds,
    '',
    '\tstatic var FONTS = "%s";' % js_string(meta['fonts']),
    '}',
    '',
]
os.makedirs(os.path.dirname(DST), exist_ok=True)
open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('Data.hx %d bytes (fonts %d, texts %d, levels %d)' % (sum(len(l) + 1 for l in lines), len(js_string(meta['fonts'])),
                                                             len(meta['texts']), len(meta['league'])))
