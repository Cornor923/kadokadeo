"""Writes trigo/Data.hx from the asset pipeline output (clips.json, meta.json).
usage: trigo_data.py <out dir of trigo_assets.py> <Data.hx>"""
import sys, json, os

OUT, DST = sys.argv[1], sys.argv[2]
clips = json.load(open(os.path.join(OUT, 'clips.json')))
meta = json.load(open(os.path.join(OUT, 'meta.json')))


def js_string(v):
    """JSON in a double quoted Haxe string (no interpolation in those)"""
    s = json.dumps(v, separators=(',', ':'), ensure_ascii=True)
    return s.replace('\\', '\\\\').replace('"', '\\"')


def floats(a):
    return '[' + ', '.join(repr(float(v)) for v in a) + ']'


names = meta['clipNames']
num = meta['num']
lines = [
    'package trigo;',
    '',
    '// generated by .opencode/skills/flash-port/scripts/examples/trigo/trigo_data.py from the original gfx.swf (do not edit)',
    'class Data {',
    '\tstatic var _clips:Dynamic = null;',
    '\tstatic var _fonts:Dynamic = null;',
    '',
    '\t// timelines of the symbols of gfx.swf (see arkadeo.Clip)',
    '\tpublic static function clips():Dynamic {',
    '\t\tif (_clips == null)',
    '\t\t\t_clips = haxe.Json.parse(CLIPS);',
    '\t\treturn _clips;',
    '\t}',
    '',
    '\t// the glyphs of the texts (arkadeo.TextField): the number of the combo meter (num: Fredoka One 120 embedded, its',
    '\t// drop shadows baked) and the device font "arial" of Game.showText, bold, 18 to 24 (a18 ... a24)',
    '\tpublic static function fonts():Dynamic {',
    '\t\tif (_fonts == null)',
    '\t\t\t_fonts = haxe.Json.parse(FONTS);',
    '\t\treturn _fonts;',
    '\t}',
    '',
    '\t// the clips of the gfx.* classes',
]
for k, n in (('Blocks', 'BLOCKS'), ('Blocks2', 'BLOCKS2'), ('Clock', 'CLOCK'), ('ComboMeter', 'COMBO_METER'),
             ('Part', 'PART')):
    lines.append('\tpublic static inline var %s = "%s";' % (n, names[k]))
blk = meta['blk']
lines += [
    '',
    '\t// Game.flatten of a block (picture `blk` 1 + colour, + 5 for a gfx.Blocks2): the top left of its bounds, where the',
    '\t// Bitmap is put',
    '\tpublic static var BLK_X:Array<Float> = %s;' % floats([b[0] for b in blk]),
    '\tpublic static var BLK_Y:Array<Float> = %s;' % floats([b[1] for b in blk]),
    '',
    '\t// the `_txt` field of the boxes _current / _next of the combo meter: its box from (0, 0) of the box clip, its width',
    '\t// (the text centred)',
    '\tpublic static inline var NUM_X = %r;' % float(num['x'] + num['bounds'][0]),
    '\tpublic static inline var NUM_Y = %r;' % float(num['y'] + num['bounds'][2]),
    '\tpublic static inline var NUM_W = %r;' % round(float(num['bounds'][1] - num['bounds'][0]), 4),
    '',
    '\tstatic var CLIPS = "%s";' % js_string(clips),
    '\tstatic var FONTS = "%s";' % js_string(meta['fonts']),
    '}',
    '',
]
os.makedirs(os.path.dirname(DST), exist_ok=True)
open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('Data.hx %d bytes (clips %d, fonts %d)' % (sum(len(l) + 1 for l in lines), len(js_string(clips)),
                                               len(js_string(meta['fonts']))))
