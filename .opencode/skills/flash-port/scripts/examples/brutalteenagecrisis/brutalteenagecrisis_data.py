"""Brutal Teenage Crisis: out/meta.json (brutalteenagecrisis_assets.py) -> resources/hx/games/brutalteenagecrisis/Data.hx
usage: brutalteenagecrisis_data.py <out folder> <Data.hx>
"""
import os, sys, json

OUT, DEST = sys.argv[1], sys.argv[2]
m = json.load(open(os.path.join(OUT, 'meta.json')))


def s(v):
    return json.dumps(v)


def rects(d):
    return ',\n'.join('\t\t%s => [%s]' % (s(k), ', '.join(str(n) for n in v)) for k, v in sorted(d.items()))


anims = ',\n'.join('\t\t{g: %s, d: %s, t: %s}' % (s(a['g']), s(a['d']), 'null' if a['t'] is None else a['t']) for a in m['anims'])
level = ',\n'.join('\t\t%s' % s(r) for r in m['level'])

code = '''package brutalteenagecrisis;

// Generated by .opencode/skills/flash-port/scripts/examples/brutalteenagecrisis/brutalteenagecrisis_data.py from the
// atlases of the Arkadeo game: do not edit, run rebuild_assets.sh.
class Data {
	// sheet.anims.xml: group, definition (BLib.parseAnimDefinition), timing (null: 1 frame each)
	public static final ANIMS:Array<{g:String, d:String, t:Null<Int>}> = [
%s
	];

	// testLevel.png as read by Level.readFromFile(0): '#' white (wall), 'H' red (ladder), '.' anything else;
	// %d rows of %d cells (the last one is only read as "the pixel under")
	public static final LEVEL:Array<String> = [
%s
	];

	// the attach colours in the frames of the sheet (Hero: hair 0x00bdff, chain 0x18fff7), as getColorBoundsRect
	// found them: "group#frame" => [x, y, width, height]
	public static final HAIR:Map<String, Array<Int>> = [
%s
	];
	public static final CHAIN:Map<String, Array<Int>> = [
%s
	];
}
''' % (anims, len(m['level']), len(m['level'][0]), level, rects(m['attach']['hair']), rects(m['attach']['chain']))

os.makedirs(os.path.dirname(DEST), exist_ok=True)
open(DEST, 'w', newline='\n').write(code)
print('Data.hx: %d anims, %d rows, %d + %d attach frames' % (len(m['anims']), len(m['level']), len(m['attach']['hair']), len(m['attach']['chain'])))
