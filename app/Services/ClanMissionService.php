// the collaborative missions of the clans: a score (a palier of the stars) to reach on several games within
// ClanSettings::$mission_hours, more games in a bigger clan, higher paliers with each mission. A completed mission gives up
// to 10 points (one less every 10 missions) and opens the next one; a mission not finished in time loses 1 point by game
// not completed, minus one, and the clan gets a new mission of the same number. The runs of the missions are free. The
// members see the changes at once (App\Events\ClanUpdated), a toast for a step done and for the next mission available
// (App\Events\ClanToast: the mission itself is made when a member opens the missions, its time starting then).
class ClanMissionService
{
    public function __construct(private readonly ClanService $clanService) {}

    // the mission in progress (a new one when the previous is over)
    public function currentMission(Clan $clan, ?Period $period = null): ?ClanMission
    {
        $period ??= $this->clanService->currentPeriod();
        if (!$period) {
            return null;
        }

        $this->failExpired($clan, $period);

        $mission = ClanMission::query()
            ->where('clan_id', $clan->id)
            ->where('period_id', $period->id)
            ->where('status', ClanMission::ACTIVE)
            ->first();

        if (!$mission && $period->end_at->isFuture()) {
            $mission = $this->generateMission($clan, $period);
        }

        return $mission;
    }

    // "Régénérer la mission" (admin): the mission in progress replaced by a new one of the same number, made with the
    // settings of now, without losing any point (as the "Mission suivante" option)
    public function regenerateMission(Clan $clan): ClanMission
    {
        $period = $this->clanService->assertPeriod();
        $this->failExpired($clan, $period);

        return DB::transaction(function () use ($clan, $period) {
            $mission = ClanMission::query()->where('clan_id', $clan->id)->where('period_id', $period->id)
                ->where('status', ClanMission::ACTIVE)->first();
            if ($mission) {
                $this->loseMission($mission, ClanMission::SKIPPED);
            }

            return $this->generateMission($clan, $period);
        });
    }

    // the missions not finished in time are failed (also every 5 minutes, kado:clans:expire-missions: the members are told
    // a new mission is there without opening the missions)
    public function failExpired(Clan $clan, Period $period): void
    {
        $expired = ClanMission::query()
            ->where('clan_id', $clan->id)
            ->where('period_id', $period->id)
            ->where('status', ClanMission::ACTIVE)
            ->where('expires_at', '<=', now())
            ->get();
        foreach ($expired as $mission) {
            $this->loseMission($mission, ClanMission::FAILED);
        }
    }

    // the number of the mission: one more than the missions completed in the period
    public function generateMission(Clan $clan, Period $period): ClanMission
    {
        return DB::transaction(function () use ($clan, $period) {
            $score = $this->clanService->periodScore($clan, $period);
            $score = $score->newQuery()->lockForUpdate()->find($score->id);
            // generated by another request in the meantime
            $active = ClanMission::query()->where('clan_id', $clan->id)->where('period_id', $period->id)
                ->where('status', ClanMission::ACTIVE)->where('expires_at', '>', now())->first();
            if ($active) {
                return $active;
            }

            $number = $score->missions_completed + 1;
            $mission = ClanMission::query()->create([
                'clan_id' => $clan->id,
                'period_id' => $period->id,
                'number' => $number,
                'status' => ClanMission::ACTIVE,
                'expires_at' => now()->addHours(app(ClanSettings::class)->mission_hours),
            ]);

            // steps of all the difficulties, in no order
            $paliers = ClanMissionPaliers::fromSettings(app(ClanSettings::class));
            $lists = $this->gameLists($clan, $period);
            $games = $this->pickGames($this->stepsCount($clan->members()->count(), $number), $lists['banned'], $lists['forced']);
            $levels = collect($paliers->levels($number, $games->count()))->shuffle()->values();
            foreach ($games as $index => $game) {
                $mission->steps()->create([
                    'game_id' => $game->id,
                    'target_score' => $paliers->targetScore($game, $levels[$index]),
                ]);
            }
            ClanUpdated::send([$clan->id], [ClanUpdated::MISSIONS]);

            return $mission->load('steps');
        });
    }

    public function startStep(User $user, ClanMissionStep $step): ClanAction
    {
        $mission = $step->mission;
        $this->clanService->assertMember($user, $mission->clan);
        if ($mission->status !== ClanMission::ACTIVE || $mission->expires_at->isPast()) {
            throw new ClanException('Cette mission est terminée.');
        }
        if ($step->isDone()) {
            throw new ClanException('Cette étape a déjà été réussie.');
        }

        $this->clanService->forgetUnplayedActions($user);

        return ClanAction::query()->create([
            'clan_id' => $mission->clan_id,
            'user_id' => $user->id,
            'game_id' => $step->game_id,
            'type' => ClanActionType::MISSION,
            'clan_mission_step_id' => $step->id,
        ]);
    }

    // "Je m'en occupe": a member says he will complete the step later. Any member can take the place, the one who reserved
    // can give it up (only an information for the clan).
    public function reserveStep(User $user, ClanMissionStep $step): void
    {
        $mission = $step->mission;
        $this->clanService->assertMember($user, $mission->clan);
        if ($mission->status !== ClanMission::ACTIVE || $mission->expires_at->isPast()) {
            throw new ClanException('Cette mission est terminée.');
        }
        if ($step->isDone()) {
            throw new ClanException('Cette étape a déjà été réussie.');
        }

        $step->update($step->reserved_by_user_id === $user->id
            ? ['reserved_by_user_id' => null, 'reserved_at' => null]
            : ['reserved_by_user_id' => $user->id, 'reserved_at' => now()]);
        ClanUpdated::send([$mission->clan_id], [ClanUpdated::MISSIONS]);
    }

    // a step completed gives a point to its player in the ranking of the clan
    public function completeStep(ClanAction $action, Run $run): string
    {
        return DB::transaction(function () use ($action, $run) {
            $step = ClanMissionStep::query()->lockForUpdate()->findOrFail($action->clan_mission_step_id);
            $mission = ClanMission::query()->lockForUpdate()->findOrFail($step->clan_mission_id);

            if ($step->isDone() || $mission->status !== ClanMission::ACTIVE || $mission->expires_at->isPast()) {
                return 'too_late';
            }
            if ($run->score < $step->target_score) {
                return 'failed';
            }

            $step->update([
                'completed_by_user_id' => $action->user_id,
                'run_id' => $run->id,
                'score' => $run->score,
                'completed_at' => now(),
            ]);
            $this->clanService->memberStat($mission->clan_id, $action->user_id, $mission->period_id)->increment('mission_steps');
            ClanUpdated::send([$mission->clan_id], [ClanUpdated::MISSIONS, ClanUpdated::HISTORY]);
            $player = User::query()->find($action->user_id);
            if ($player && $step->game) {
                Realtime::send(ClanToast::stepCompleted($mission->clan_id, $player, $step->game, (int) $run->score));
            }
            $this->completeMissionIfDone($mission);

            return 'completed';
        });
    }

    // a run found cheated after it completed a step (RunService::flagAsCheat): the step is to do again while its mission
    // goes on. A mission already completed keeps its points (an admin decides)
    public function revertCheatedRun(Run $run): void
    {
        DB::transaction(function () use ($run) {
            $steps = ClanMissionStep::query()->where('run_id', $run->id)->whereNotNull('completed_at')->lockForUpdate()->get();
            foreach ($steps as $step) {
                $mission = ClanMission::query()->lockForUpdate()->find($step->clan_mission_id);
                if (!$mission || $mission->status !== ClanMission::ACTIVE) {
                    continue;
                }
                ClanMemberStat::query()
                    ->where(['clan_id' => $mission->clan_id, 'user_id' => $step->completed_by_user_id, 'period_id' => $mission->period_id])
                    ->where('mission_steps', '>', 0)
                    ->decrement('mission_steps');
                $step->update(['completed_by_user_id' => null, 'run_id' => null, 'score' => null, 'completed_at' => null]);
                ClanUpdated::send([$mission->clan_id], [ClanUpdated::MISSIONS, ClanUpdated::HISTORY]);
            }
        });
    }

    // not finished in time (or left at the end of the period): 1 point lost by step not completed, minus one. Replaced by
    // "Mission suivante": nothing lost.
    public function loseMission(ClanMission $mission, string $status): void
    {
        DB::transaction(function () use ($mission, $status) {
            $mission = ClanMission::query()->lockForUpdate()->find($mission->id);
            if (!$mission || $mission->status !== ClanMission::ACTIVE) {
                return;
            }

            $lost = 0;
            if ($status === ClanMission::FAILED) {
                $score = $this->clanService->periodScore($mission->clan, $mission->period);
                $missed = $mission->steps()->get()->reject(fn (ClanMissionStep $step) => $step->isDone())->count();
                $lost = min($score->mission_score, max(0, $missed - 1));
                $score->decrement('mission_score', $lost);
            }
            $mission->update(['status' => $status, 'points' => -$lost]);
            $this->missionEnded($mission);
        });
    }

    // the next mission can be opened (not after the end of the period: the tournament starts again)
    private function missionEnded(ClanMission $mission): void
    {
        ClanUpdated::send([$mission->clan_id], [ClanUpdated::MISSIONS, ClanUpdated::HISTORY]);
        if ($mission->period?->end_at?->isFuture()) {
            Realtime::send(ClanToast::missionAvailable($mission->clan_id));
        }
    }

    // the points of a completed mission: one less every ClanSettings::$mission_points_every missions (1 to 9: 10, 10 to
    // 19: 9...)
    public function missionPoints(int $number): int
    {
        $settings = app(ClanSettings::class);

        return max($settings->mission_points_min, $settings->mission_points_first - intdiv($number, max(1, $settings->mission_points_every)));
    }

    // the steps of a mission: more in a bigger clan, (maybe) fewer with each mission
    public function stepsCount(int $membersCount, int $number): int
    {
        $settings = app(ClanSettings::class);
        $base = min($settings->mission_steps_max, $settings->mission_steps_base + max(0, $membersCount - 1) * $settings->mission_steps_per_member);

        return max($settings->mission_steps_min, (int) round($base * $settings->mission_steps_ratio ** ($number - 1)));
    }

    // ---------------------------------------------------------------- bonuses

    /**
     * @param  array{game_id?: int, step_id?: int}  $params
     */
    public function useBonus(User $user, ClanBonus $bonus, array $params = []): void
    {
        $clan = $bonus->clan;
        $this->clanService->assertManager($user, $clan);
        $this->assertUsable($bonus);
        $period = $this->clanService->assertPeriod();

        DB::transaction(function () use ($bonus, $clan, $period, $params) {
            // the option locked and read again: two clicks at the same time use it once
            $bonus = ClanBonus::query()->lockForUpdate()->findOrFail($bonus->id);
            $this->assertUsable($bonus);
            $mission = $this->currentMission($clan, $period);
            // the game added to the "Jeux caca" or the "Jeux cool"
            $gameId = null;
            if (!$mission && in_array($bonus->type, [ClanBonusType::MORE_TIME, ClanBonusType::SKIP_STEP], true)) {
                throw new ClanException('Aucune mission en cours.');
            }

            switch ($bonus->type) {
                case ClanBonusType::NEXT_MISSION:
                    // a new mission of the same number, without losing points
                    if ($mission) {
                        $this->loseMission($mission, ClanMission::SKIPPED);
                    }
                    $this->generateMission($clan, $period);
                    break;
                case ClanBonusType::BAN_GAME:
                case ClanBonusType::FORCE_GAME:
                    $gameId = $this->addToGameList($bonus, $period, $params['game_id'] ?? null);
                    break;
                case ClanBonusType::MORE_TIME:
                    $mission = $this->lockActiveMission($mission);
                    $mission->update(['expires_at' => $mission->expires_at->addHours(app(ClanSettings::class)->mission_more_time_hours)]);
                    break;
                case ClanBonusType::SKIP_STEP:
                    // the step, then the mission locked, as when a run completes it (completeStep)
                    $step = $mission->steps()->whereKey($params['step_id'] ?? 0)->lockForUpdate()->first();
                    $mission = $this->lockActiveMission($mission);
                    if (!$step || $step->isDone()) {
                        throw new ClanException('Choisissez une étape de la mission en cours qui n\'est pas encore réussie.');
                    }
                    $step->update(['skipped' => true]);
                    $this->completeMissionIfDone($mission);
                    break;
            }

            $bonus->update(['used_at' => now(), 'game_id' => $gameId]);
            ClanUpdated::send([$clan->id], [ClanUpdated::MISSIONS]);
        });
    }

    // the "Jeux caca" (never in the next missions of the period) and the "Jeux cool" (in the next missions first): the
    // games of the options used, in the order they were added
    /**
     * @return array{banned: \Illuminate\Support\Collection<int, int>, forced: \Illuminate\Support\Collection<int, int>}
     */
    public function gameLists(Clan $clan, Period $period): array
    {
        $games = ClanBonus::query()
            ->where('clan_id', $clan->id)
            ->where('period_id', $period->id)
            ->whereNotNull('game_id')
            ->orderBy('used_at')
            ->orderBy('id')
            ->get(['type', 'game_id']);

        return [
            'banned' => $games->where('type', ClanBonusType::BAN_GAME)->pluck('game_id')->values(),
            'forced' => $games->where('type', ClanBonusType::FORCE_GAME)->pluck('game_id')->values(),
        ];
    }

    // ---------------------------------------------------------------- internals

    // a "Jeu caca" or a "Jeu cool" adds its game to its list: a game is in one list at most, once
    // (clan_bonuses: unique clan_id, period_id, game_id)
    private function addToGameList(ClanBonus $bonus, Period $period, ?int $gameId): int
    {
        $game = $this->activeGame($gameId);
        // the clan is locked: two options used at the same time can't add the same game
        Clan::query()->lockForUpdate()->find($bonus->clan_id);
        $lists = $this->gameLists($bonus->clan, $period);
        $isBan = $bonus->type === ClanBonusType::BAN_GAME;
        [$same, $opposite] = $isBan ? [$lists['banned'], $lists['forced']] : [$lists['forced'], $lists['banned']];

        if ($same->contains($game->id)) {
            throw new ClanException($isBan ? 'Ce jeu est déjà un jeu caca du clan.' : 'Ce jeu est déjà un jeu cool du clan.');
        }
        if ($opposite->contains($game->id)) {
            throw new ClanException($isBan
                ? 'Ce jeu est un jeu cool du clan : il ne peut pas être aussi un jeu caca.'
                : 'Ce jeu est un jeu caca du clan : il ne peut pas être aussi un jeu cool.');
        }

        return $game->id;
    }

    // the mission locked by the caller, read again: still in progress
    private function lockActiveMission(ClanMission $mission): ClanMission
    {
        $mission = ClanMission::query()->lockForUpdate()->find($mission->id);
        if (!$mission || $mission->status !== ClanMission::ACTIVE || $mission->expires_at->isPast()) {
            throw new ClanException('Aucune mission en cours.');
        }

        return $mission;
    }

    // all the steps done in time: the points of the mission, maybe an option, and the next mission (the mission locked by
    // the caller)
    private function completeMissionIfDone(ClanMission $mission): void
    {
        $mission->refresh();
        // (completed or lost meanwhile: its points are given once)
        if ($mission->status !== ClanMission::ACTIVE
            || $mission->steps()->get()->contains(fn (ClanMissionStep $step) => !$step->isDone())) {
            return;
        }

        $points = $this->missionPoints($mission->number);
        $score = $this->clanService->periodScore($mission->clan, $mission->period);
        $score->increment('mission_score', $points);
        $score->increment('missions_completed');
        $mission->update(['status' => ClanMission::COMPLETED, 'points' => $points, 'completed_at' => now()]);
        $this->missionEnded($mission);

        if (randomNumber() < app(ClanSettings::class)->bonus_chance) {
            ClanBonus::query()->create([
                'clan_id' => $mission->clan_id,
                'period_id' => $mission->period_id,
                'clan_mission_id' => $mission->id,
                'type' => $this->randomBonusType(),
            ]);
        }
    }

    // by the chances of ClanSettings::$bonus_weights
    private function randomBonusType(): ClanBonusType
    {
        $settings = app(ClanSettings::class);
        $weights = collect(ClanBonusType::cases())->mapWithKeys(fn (ClanBonusType $type) => [$type->value => $settings->bonusWeight($type)]);
        $draw = randomNumber() * $weights->sum();
        foreach ($weights as $type => $weight) {
            $draw -= $weight;
            if ($draw < 0) {
                return ClanBonusType::from($type);
            }
        }

        return ClanBonusType::from($weights->keys()->last());
    }

    private function assertUsable(ClanBonus $bonus): void
    {
        if ($bonus->used_at !== null) {
            throw new ClanException('Cette option a déjà été utilisée.');
        }
        if ($bonus->period_id !== $this->clanService->currentPeriod()?->id) {
            throw new ClanException('Les options sont remises à zéro à la fin du tournoi des clans.');
        }
    }

    private function activeGame(?int $gameId): Game
    {
        $game = $gameId ? Game::query()->where('is_active', true)->find($gameId) : null;
        if (!$game) {
            throw new ClanException('Choisissez un jeu.');
        }

        return $game;
    }

    // the "Jeux cool" first (some of them at random when there are more than the steps), then other games at random,
    // never a "Jeu caca"
    /**
     * @param  \Illuminate\Support\Collection<int, int>  $bannedIds
     * @param  \Illuminate\Support\Collection<int, int>  $forcedIds
     * @return \Illuminate\Support\Collection<int, Game>
     */
    private function pickGames(int $count, Collection $bannedIds, Collection $forcedIds)
    {
        $games = Game::query()
            ->where('is_active', true)
            ->where('is_arkadeo', false)
            ->whereNotIn('id', $bannedIds)
            ->get()
            ->filter(fn (Game $game) => is_array($game->stars) && count($game->stars) >= 3)
            ->shuffle();
        [$forced, $others] = $games->partition(fn (Game $game) => $forcedIds->contains($game->id));

        return $forced->concat($others)->take($count)->values();
    }
}
